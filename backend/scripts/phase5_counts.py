"""Acceptance item 3: class counts and the launch-date histogram per class.

    python -m scripts.phase5_counts        # writes reports/phase5_counts.md

Also checks the one thing the brief singled out: that no class is
concentrated in one month, which would turn the temporal split into a
class split.
"""
from __future__ import annotations

import json
from collections import Counter, defaultdict
from pathlib import Path

from sqlalchemy import text

from blocklens.label.rules import RULE_VERSION
from blocklens.sampling import design as d
from blocklens.store.db import session_factory

OUT = Path("reports/phase5_counts.md")
CLASSES = ("RUG", "FAILED", "SURVIVED", "UNCLEAR", "NEVER_LAUNCHED")


def main() -> int:
    with session_factory()() as s:
        rows = s.execute(text("""
            select s.sampling_stratum, s.launch_ts, s.family_id, l.label
            from token_sample s
            join token_label l on l.token_address = s.token_address and l.chain = s.chain
                               and l.rule_version = :rv
            where s.chain = 'base' and s.sampling_stratum <> 'phase2'
              and s.alive_at_cutoff
        """), {"rv": RULE_VERSION}).all()
        funnel = s.execute(text("""
            select sampling_stratum, count(*),
                   count(*) filter (where excluded_reason is null or alive_at_cutoff),
                   count(*) filter (where alive_at_cutoff)
            from token_sample where chain = 'base' and sampling_stratum <> 'phase2'
            group by 1 order by 1
        """)).all()
    windows = json.loads(Path("reports/phase5_windows.json").read_text(encoding="utf8"))["windows"]

    L = ["# Phase 5 — class counts and launch dates", "",
         f"Rule `{RULE_VERSION}`, population: alive at launch + {d.CUTOFF_MINUTES} minutes. "
         f"Split date {d.SPLIT_DATE:%Y-%m-%d}. Generated by `python -m scripts.phase5_counts`.", "",
         "## Funnel", "", "| stratum | windows | pools sampled | passed screen | alive at cutoff |",
         "|---|---|---|---|---|"]
    wn = Counter(v["stratum"] for v in windows.values())
    for st, n, passed, alive in funnel:
        L.append(f"| {st} | {wn.get(st.split('_')[0], '-') if st.startswith('train') else wn.get(st, '-')} "
                 f"| {n:,} | {passed:,} | {alive:,} |")

    L += ["", "## Class counts, by stratum and side of the split", "",
          "| stratum | side | " + " | ".join(CLASSES) + " | families (RUG) |",
          "|---|---|" + "---|" * len(CLASSES) + "---|"]
    table = defaultdict(Counter)
    fam = defaultdict(set)
    for st, ts, f, lab in rows:
        side = "before" if ts < d.SPLIT_DATE else "after"
        table[(st, side)][lab] += 1
        if lab == "RUG":
            fam[(st, side)].add(f)
    for key in sorted(table):
        c = table[key]
        L.append(f"| {key[0]} | {key[1]} | " + " | ".join(str(c[k]) for k in CLASSES)
                 + f" | {len(fam[key])} |")

    L += ["", "## Launch month, per class (all sampled, labelled, alive tokens)", ""]
    months = sorted({ts.strftime("%Y-%m") for _, ts, _, _ in rows})
    L += ["| class | " + " | ".join(months) + " | max share in one month |",
          "|---|" + "---|" * len(months) + "---|"]
    worst = {}
    for lab in CLASSES:
        c = Counter(ts.strftime("%Y-%m") for _, ts, _, l in rows if l == lab)
        tot = sum(c.values())
        if not tot:
            continue
        share = max(c.values()) / tot
        worst[lab] = share
        L.append(f"| {lab} | " + " | ".join(str(c[m]) for m in months) + f" | {share:.0%} |")
    L += ["", "Per stratum:", ""]
    for st in sorted({r[0] for r in rows}):
        L += [f"**{st}**", "", "| class | " + " | ".join(months) + " |",
              "|---|" + "---|" * len(months)]
        for lab in ("RUG", "FAILED", "SURVIVED"):
            c = Counter(ts.strftime("%Y-%m") for s_, ts, _, l in rows if l == lab and s_ == st)
            if sum(c.values()):
                L.append(f"| {lab} | " + " | ".join(str(c[m]) for m in months) + " |")
        L.append("")
    flag = [k for k, v in worst.items() if v > 0.5 and k in ("RUG", "FAILED", "SURVIVED")]
    L += ["## Concentration check", "",
          ("No outcome class has more than half its tokens in one launch month."
           if not flag else
           "**Concentrated:** " + ", ".join(f"{k} ({worst[k]:.0%} in one month)" for k in flag)
           + ". The temporal split must be read with this in mind.")]
    OUT.write_text("\n".join(L) + "\n", encoding="utf8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
